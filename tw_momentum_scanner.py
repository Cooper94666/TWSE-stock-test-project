    def get_stock_data(self, stock_id, period='60d'):
        """從 Yahoo Finance 獲取股票資料"""
        try:
            ticker = f"{stock_id}.TW"
            stock = yf.Ticker(ticker)
            hist = stock.history(period=period)
            
            if hist.empty or len(hist) < 5:
                return None
            
            volume = hist['Volume']
            close = hist['Close']
            turnover = volume * close
            
            df = pd.DataFrame({
                'date': hist.index,
                'stock_id': stock_id,
                'open': hist['Open'],
                'high': hist['High'],
                'low': hist['Low'],
                'close': hist['Close'],
                'volume': hist['Volume'],
                'turnover': turnover
            })
            return df
        except Exception:
            return None

